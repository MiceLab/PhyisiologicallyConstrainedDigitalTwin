"""
Export the shipped decoders (twin.RUNS) for the static GitHub Pages explorer in docs/.

Writes docs/models/<dataset>.json: the decoder weights as little-endian float32 base64, the
run's latent dynamics and pi/ra scaling, and a reference day generated by app.py's own code.
docs/selftest.mjs replays that day in JS and fails if the browser port drifts from TF.

Run in the requirements.txt environment:  python export_web.py && node docs/selftest.mjs
"""
import base64
import json
import os

import numpy as np

import app
from twin import RUNS, PI_RA_MAX, ROOT

OUT = os.path.join(ROOT, 'docs', 'models')
LAYERS = ['dense_5', 'dense_6', 'time_distributed', 'dense_8', 'dense_9', 'dense_10',
          'time_distributed_1', 'dense_12']


def b64(a):
    return base64.b64encode(np.ascontiguousarray(a, dtype='<f4').tobytes()).decode()


def reference_day(dataset, run):
    """Frozen latent (the browser's PRNG is not numpy's), full overlap, two meals and a bolus."""
    app.build(dataset, run['model'], run['epoch'])
    app.S['latent_mode'], app.S['overlap'] = 'frozen', app.S['after']
    z = [0.5, -1.0, 0.3, 1.2][:app.S['latent_dim']]
    b = app.S['before']
    app.S['cho'][b + 12], app.S['bolus'][b + 12], app.S['cho'][b + 100] = 60.0, 6.0, 30.0
    app.refresh_inputs()
    app.run_all(app.latent(z))
    return dict(z=z, cho={12: 60.0, 100: 30.0}, bolus={12: 6.0},
                pi=app.S['pi'].tolist(), ra=app.S['ra'].tolist(), bg=app.S['bg'])


def export(dataset, run):
    app.build(dataset, run['model'], run['epoch'])
    decoder = app.S['decoder']
    assert [i.name.split(':')[0] for i in decoder.inputs] == ['in_lat', 'in_pi', 'in_ra'], \
        'docs/twin.js hard-codes the in_lat/in_pi/in_ra decoder; this one differs'
    cfg = app._cfg(run['model'])
    weights = {}
    for name in LAYERS:
        kernel, bias = decoder.get_layer(name).get_weights()
        weights[name] = dict(n_in=kernel.shape[0], k=b64(kernel), b=b64(bias))
    return dict(dataset=dataset, model=run['model'], epoch=run['epoch'],
                latent_phi=run['latent_phi'], latent_scale=run['latent_scale'],
                pi_max=PI_RA_MAX[dataset][0], ra_max=PI_RA_MAX[dataset][1],
                before=app.S['before'], after=app.S['after'],
                min_gain=cfg['min_gain_mgdl'], control_scale=cfg['control_scale'],
                weights=weights, reference=reference_day(dataset, run))


if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    for dataset, run in RUNS.items():
        path = os.path.join(OUT, f'{dataset}.json')
        with open(path, 'w') as f:
            json.dump(export(dataset, run), f)
        print('wrote', path)
